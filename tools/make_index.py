#!/usr/bin/env python3
"""Regenerate gta6decomp/INDEX.md from index.tsv.

The exporter appends one row per written function, so the index is a journal, not a
plan: it lists what was actually recovered, grouped by the subsystem the exporter
inferred. Re-running is cheap and idempotent.

Usage: python3 tools/make_index.py [root]
"""
import os
import sys
from collections import defaultdict

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..")
TSV = os.path.join(ROOT, "index.tsv")
OUT = os.path.join(ROOT, "INDEX.md")


def main():
    if not os.path.exists(TSV):
        print(f"no {TSV}; nothing exported yet")
        return 1

    rows = []
    with open(TSV, encoding="utf-8") as fh:
        header = fh.readline().rstrip("\n").split("\t")
        for line in fh:
            line = line.rstrip("\n")
            if not line:
                continue
            parts = line.split("\t")
            if len(parts) != len(header):
                continue
            rows.append(dict(zip(header, parts)))

    by_sub = defaultdict(list)
    for r in rows:
        by_sub[r["subsystem"]].append(r)

    total_bytes = 0
    for r in rows:
        try:
            total_bytes += int(r["size"])
        except ValueError:
            pass

    lines = [
        "# gta6decomp index",
        "",
        f"{len(rows)} recovered functions, {total_bytes:,} bytes of code, "
        f"{len(by_sub)} subsystems.",
        "",
        "Generated by `tools/make_index.py` from `index.tsv`. Subsystems are inferred from the",
        "RAGE asset paths a function (or its direct callees) references, so they are a reading",
        "aid, not a claim about the original class hierarchy.",
        "",
        "| Subsystem | Functions | Bytes |",
        "|---|---:|---:|",
    ]
    for sub in sorted(by_sub):
        rs = by_sub[sub]
        b = 0
        for r in rs:
            try:
                b += int(r["size"])
            except ValueError:
                pass
        lines.append(f"| [{sub}](#{sub.replace('/', '')}) | {len(rs)} | {b:,} |")

    for sub in sorted(by_sub):
        lines += ["", f"## {sub}", "", "| Function | Address | Bytes | Strings | File |",
                  "|---|---|---:|---:|---|"]
        for r in sorted(by_sub[sub], key=lambda x: x["name"]):
            lines.append(
                f"| `{r['name']}` | `{r['address']}` | {r['size']} | {r['strings']} | "
                f"[{os.path.basename(r['file'])}]({r['file']}) |"
            )

    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(rows)} functions across {len(by_sub)} subsystems")
    return 0


if __name__ == "__main__":
    sys.exit(main())
